export default async function handler(req, res) {
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Access-Control-Allow-Methods", "GET, POST, OPTIONS");
  res.setHeader("Access-Control-Allow-Headers", "Content-Type");

  if (req.method === "OPTIONS") {
    return res.status(200).end();
  }

  if (req.method === "GET") {
    return res.status(200).json({ dates: Object.keys(ARCHIVE) });
  }

  if (req.method !== "POST") {
    return res.status(405).json({ error: "Method not allowed" });
  }

  const { date } = req.body || {};

  if (!date) {
    return res.status(400).json({ error: "Missing date parameter" });
  }

  if (ARCHIVE[date]) {
    return res.status(200).json({ articles: ARCHIVE[date], source: "archive" });
  }

  const apiKey = process.env.ANTHROPIC_API_KEY;
  if (!apiKey) {
    return res.status(404).json({ error: "Date not in archive and no API key configured." });
  }

  try {
    const response = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "x-api-key": apiKey,
        "anthropic-version": "2023-06-01",
        "anthropic-beta": "web-search-2025-03-05"
      },
      body: JSON.stringify({
        model: "claude-opus-4-5",
        max_tokens: 4000,
        tools: [{ type: "web_search_20250305", name: "web_search" }],
        messages: [
          {
            role: "user",
            content: `Search for the top 6 most significant AI news stories from ${date}. Return ONLY a valid JSON array with no markdown, no explanation, and no surrounding text. Each object must have exactly these keys: headline (max 10 words, punchy newspaper style), category (one of: MODELS, FUNDING, INDUSTRY, PRODUCTS, POLICY, RESEARCH), dateline (city name in caps or GLOBAL), summary (2-3 tight factual sentences with specific details and numbers), source (publication name), url (direct link to article). Use real stories with real URLs from that date.`
          }
        ]
      })
    });

    const data = await response.json();
    const textContent = data.content?.find(b => b.type === "text")?.text || "";
    const clean = textContent.replace(/```json|```/g, "").trim();
    const articles = JSON.parse(clean);

    return res.status(200).json({ articles, source: "live" });
  } catch (err) {
    return res.status(500).json({ error: "Failed to fetch live news", details: err.message });
  }
}
